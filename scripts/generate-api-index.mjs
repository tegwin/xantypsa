// ============================================================
// Generate docs/API-INDEX.md from the route files
// ============================================================
// Hand-written API docs go stale the moment a route is added. This walks
// src/app/api and lists what actually exists, so the index is never a lie.
// Re-run it whenever a route is added, changed or removed.

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const API_DIR = 'src/app/api';
const VERBS = ['GET', 'POST', 'PATCH', 'PUT', 'DELETE'];

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (entry === 'route.ts') out.push(full);
  }
  return out;
}

const rows = [];
for (const file of walk(API_DIR).sort()) {
  const src = readFileSync(file, 'utf8');
  const verbs = VERBS.filter((v) =>
    new RegExp(`export\\s+(const|async\\s+function|function)\\s+${v}\\b`).test(src),
  );
  // The module and permission a route is guarded by, as passed to withTenant.
  const guard = src.match(/\}, '([a-z_]+)', '(read|write|delete)'\)/);
  const path = '/' + relative(API_DIR, file).replace(/\/route\.ts$/, '').replace(/\\/g, '/');
  rows.push({
    path: '/api' + (path === '/.' ? '' : path),
    verbs,
    module: guard ? guard[1] : '',
  });
}

const lines = [
  '# API index',
  '',
  'Generated by `node scripts/generate-api-index.mjs`. Do not edit by hand.',
  '',
  `Every route under \`src/app/api\`, ${rows.length} in total.`,
  '',
  'Authentication, error shapes and conventions are in [API.md](API.md).',
  '',
  '| Endpoint | Methods | Module |',
  '|---|---|---|',
  ...rows.map((r) => `| \`${r.path}\` | ${r.verbs.join(', ') || '-'} | ${r.module || '-'} |`),
  '',
];

writeFileSync('docs/API-INDEX.md', lines.join('\n'));
console.log(`Wrote docs/API-INDEX.md with ${rows.length} routes`);
