// ============================================================
// Generate sql/rls.sql from prisma/schema.prisma
// ============================================================
// Row-level security for the restricted role the AI's SQL tool connects as.
// Generated rather than hand-written so a new model cannot be added to the
// schema and quietly miss a policy — re-run this after any schema change.
//
//   node scripts/generate-rls.mjs
//
// The application's own role owns these tables and therefore bypasses RLS;
// nothing here changes how XantyPSA itself queries the database.

import fs from 'fs';
import path from 'path';

const SCHEMA = path.join(process.cwd(), 'prisma', 'schema.prisma');
const OUT = path.join(process.cwd(), 'sql', 'rls.sql');

/** Tables the AI role must never read, at any scope. */
const DENY = new Set(['users', 'accounts', 'sessions', 'verification_tokens']);

const src = fs.readFileSync(SCHEMA, 'utf8');
const models = [...src.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)].map(([, name, body]) => {
  const mapped = body.match(/@@map\("([^"]+)"\)/);
  const relations = [...body.matchAll(
    /^\s*\w+\s+(\w+)(\?)?\s+@relation\([^)]*fields:\s*\[(\w+)\]/gm
  )].map(([, target, optional, fk]) => ({ target, fk, optional: !!optional }));
  return {
    name,
    table: mapped ? mapped[1] : name,
    hasTenant: /^\s*tenantId\s+String/m.test(body),
    relations,
  };
});

const byName = Object.fromEntries(models.map((m) => [m.name, m]));
const TENANT = `current_setting('app.tenant_id', true)`;

/**
 * Walk relations until we reach a model carrying tenantId, so a child table is
 * scoped by whatever owns it (ContractItem -> Contract -> tenant).
 */
function resolveScope(model, seen = new Set()) {
  if (model.hasTenant) return { kind: 'direct' };
  seen.add(model.name);

  for (const rel of model.relations) {
    const parent = byName[rel.target];
    if (!parent || seen.has(parent.name) || DENY.has(parent.table)) continue;

    const scope = resolveScope(parent, seen);
    if (!scope) continue;

    const inner =
      scope.kind === 'direct'
        ? `p."tenantId" = ${TENANT}`
        : scope.sql.replace(/\bp\./g, 'gp.').replace(/AS p\b/g, 'AS gp');

    return {
      kind: 'via',
      sql: `EXISTS (SELECT 1 FROM "${parent.table}" AS p WHERE p."id" = "${rel.fk}" AND ${inner})`,
      optional: rel.optional,
      via: parent.name,
    };
  }
  return null;
}

const lines = [];
const skipped = [];
lines.push(`-- Generated by scripts/generate-rls.mjs — do not edit by hand.`);
lines.push(`-- Re-run after any change to prisma/schema.prisma.`);
lines.push('');
lines.push('BEGIN;');
lines.push('');

for (const m of models.sort((a, b) => a.table.localeCompare(b.table))) {
  const t = m.table;
  lines.push(`ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`);
  lines.push(`DROP POLICY IF EXISTS ai_tenant_isolation ON "${t}";`);

  if (DENY.has(t)) {
    // No policy at all: RLS with zero policies denies every row to non-owners.
    lines.push(`-- ${m.name}: credentials and sessions — no policy, so no rows are visible.`);
    lines.push('');
    continue;
  }

  if (t === 'tenants') {
    lines.push(`CREATE POLICY ai_tenant_isolation ON "${t}"`);
    lines.push(`  FOR SELECT USING ("id" = ${TENANT});`);
    lines.push('');
    continue;
  }

  const scope = resolveScope(m);
  if (!scope) {
    skipped.push(m.name);
    lines.push(`-- ${m.name}: no path to a tenant — denied by default.`);
    lines.push('');
    continue;
  }

  const predicate =
    scope.kind === 'direct' ? `"tenantId" = ${TENANT}` : scope.sql;

  if (scope.kind === 'via') lines.push(`-- ${m.name} is scoped through ${scope.via}.`);
  lines.push(`CREATE POLICY ai_tenant_isolation ON "${t}"`);
  lines.push(`  FOR SELECT USING (${predicate});`);
  lines.push('');
}

lines.push('COMMIT;');
lines.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));

// ------------------------------------------------------------
// The role the AI connects as
// ------------------------------------------------------------
// Kept in the same generator so the deny list can never drift between the
// policies and the grants.
const roleSql = `-- Generated by scripts/generate-rls.mjs — do not edit by hand.
--
-- The restricted role the AI's SQL tool connects as. XantyPSA itself keeps
-- using its normal role, which owns these tables and so bypasses RLS.
--
-- 1. Replace CHANGE_ME with a generated password:  openssl rand -base64 24
-- 2. Run this file, then sql/rls.sql
-- 3. Put the matching connection string in AI_DATABASE_URL

CREATE ROLE xantypsa_ai LOGIN PASSWORD 'CHANGE_ME';

GRANT USAGE ON SCHEMA public TO xantypsa_ai;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO xantypsa_ai;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO xantypsa_ai;

-- Read-only, belt and braces: RLS already blocks writes for this role because
-- no INSERT/UPDATE/DELETE policy exists, but revoke the privilege as well.
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA public FROM xantypsa_ai;

-- Credentials and sessions are unreadable at the privilege level too, not only
-- via the absent RLS policy.
REVOKE ALL ON ${[...DENY].map((t) => `"${t}"`).join(', ')} FROM xantypsa_ai;
`;
fs.writeFileSync(path.join(process.cwd(), 'sql', 'ai-role.sql'), roleSql);

console.log(`Wrote ${OUT}`);
console.log(`Wrote ${path.join(process.cwd(), 'sql', 'ai-role.sql')}`);
console.log(`  tables:        ${models.length}`);
console.log(`  denied:        ${[...DENY].join(', ')}`);
if (skipped.length) console.log(`  NO TENANT PATH (denied): ${skipped.join(', ')}`);
