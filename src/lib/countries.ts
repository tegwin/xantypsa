// What the subdivision field should be called for a given country.
const SUBDIVISION_LABELS: Record<string, string> = {
  US: 'State', AU: 'State', IN: 'State', BR: 'State', MX: 'State',
  CA: 'Province', ZA: 'Province', CN: 'Province',
  IE: 'County', GB: 'Country / Region',
  NZ: 'Region', FR: 'Region', IT: 'Region',
  DE: 'State', ES: 'Province', NL: 'Province', JP: 'Prefecture',
};

export function subdivisionLabelFor(countryName?: string | null): string {
  const code = countryCodeFor(countryName);
  return (code && SUBDIVISION_LABELS[code]) || 'State / Province / Region';
}

export function subdivisionsFor(countryName?: string | null): string[] | null {
  const code = countryCodeFor(countryName);
  return (code && SUBDIVISIONS[code]) || null;
}
