const NAME_TO_CODE: Record<string, string> = COUNTRIES.reduce((acc, c) => {
  acc[c.name.toLowerCase()] = c.code;
  return acc;
}, {} as Record<string, string>);

// Common legacy spellings already sitting in the database.
const ALIASES: Record<string, string> = {
  'uk': 'GB', 'u.k.': 'GB', 'great britain': 'GB', 'england': 'GB',
  'scotland': 'GB', 'wales': 'GB', 'northern ireland': 'GB',
  'usa': 'US', 'u.s.a.': 'US', 'united states of america': 'US', 'america': 'US',
  'uae': 'AE', 'south korea': 'KR', 'republic of ireland': 'IE',
  'rsa': 'ZA', 'holland': 'NL', 'turkey': 'TR',
};

export function countryCodeFor(countryName?: string | null): string | undefined {
  if (!countryName) return undefined;
  const key = countryName.trim().toLowerCase();
  return NAME_TO_CODE[key] || ALIASES[key];
}

